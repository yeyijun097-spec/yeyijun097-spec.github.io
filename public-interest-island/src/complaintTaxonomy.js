export function taxonomyOptions(path = []) {
  if (!path.length) return Object.keys(COMPLAINT_TAXONOMY);
  const level2 = COMPLAINT_TAXONOMY[path[0]];
  if (!level2) return [];
  if (path.length === 1) return Object.keys(level2);
  return Array.isArray(level2[path[1]]) ? level2[path[1]] : [];
}

export function parseTaxonomyPath(value = "") {
  const raw = String(value || "").trim();
  if (!raw) return [];
  const separator = raw.indexOf("/");
  if (separator < 0) return [raw];
  return [raw.slice(0, separator), raw.slice(separator + 1)].map((item) => item.trim()).filter(Boolean);
}

export function reconcileTaxonomyOptions(path = [], _liveOptions = []) {
  // 实时 DOM 结果只能用于确认兴趣岛当前页面是否仍包含已验证分类，
  // 不能直接成为复核页选项。兴趣岛大页面中同时存在侧栏菜单、订单入口
  // 和隐藏弹层，宽泛 DOM 扫描会把这些无关文字混入分类菜单。
  return taxonomyOptions(path);
}

export function suggestProblemLabels(text, relationship = "本人") {
  const value = String(text || "");
  if (relationship === "子女" || /(?:儿子|女儿|孩子|子女).{0,20}(?:投诉|退款|退费|诱导|虚假)/.test(value)) {
    if (/诱导|消费/.test(value)) return ["退费争议", "子女投诉", "子女称被诱导消费"];
    if (/虚假|夸大|宣传/.test(value)) return ["退费争议", "子女投诉", "子女称虚假夸大宣传"];
    return ["退费争议", "子女投诉", "子女对退款有争议"];
  }
  if (/(?:先|要求|让).{0,10}(?:垫付|代付)|(?:垫付|代付).{0,20}(?:返还|索取|报销)/.test(value)) {
    return ["购课问题", "诱导分期/隐形消费", "先垫付后索取"];
  }
  if (/(?:诱导|引导|要求|办理).{0,12}(?:分期|贷款)|(?:分期|贷款).{0,12}(?:诱导|引导|支付|购课)/.test(value)) {
    return ["购课问题", "诱导分期/隐形消费", "引导分期支付"];
  }
  if (/(?:诱导|引导|怂恿|哄骗).{0,12}(?:消费|购买|购课|付款|交费)|(?:被诱导|诱导消费)/.test(value)) {
    return ["购课问题", "诱导分期/隐形消费", "学员称被诱导消费"];
  }
  if (/(?:不具备|没有|无).{0,12}(?:医疗|康复|教学|办学).{0,8}(?:资质|资格|许可证)|(?:虚构|伪造).{0,8}(?:资质|资格|许可证)/.test(value)) {
    return ["虚假宣传", "课程宣传和实际不符", "虚构资质"];
  }
  if (/(?:宣传|承诺).{0,20}直播.{0,30}(?:录播|录制)|(?:录播|录制).{0,30}(?:宣传|承诺).{0,20}直播/.test(value)) {
    return ["虚假宣传", "课程宣传和实际不符", "智能直播"];
  }
  if (/(?:宣传|承诺).{0,50}(?:达不到|未达到|没有|无).{0,12}(?:效果|功效|改善)|(?:效果|功效|改善).{0,12}(?:达不到|未达到|没有|无)/.test(value)) {
    return ["虚假宣传", "夸大功效", "未达宣传效果"];
  }
  if (/虚假|夸大|宣传不符|没有改善|未达/.test(value)) {
    return /功效|效果|疗效|改善|抗衰|健康|失眠/.test(value)
      ? ["虚假宣传", "夸大功效", "未达宣传效果"]
      : ["虚假宣传", "课程宣传和实际不符", "课程节数/内容/老师"];
  }
  if (/(?:一直|至今|仍未|尚未|没有).{0,12}(?:开班|开课)|(?:开班|开课).{0,12}(?:延期|推迟|不明确|未知)/.test(value)) {
    return ["课程问题", "时间安排", "开课时间"];
  }
  if (/退费进度|退款进度|迟迟不退/.test(value)
    || /(?:答应|承诺|告知|表示).{0,24}(?:退款|退费|款).{0,24}(?:到账|退回|返还).{0,30}(?:仍未|未见|没有|没收到|联系不上)/.test(value)
    || /(?:退款|退费|款).{0,24}(?:1\s*[-至到]\s*3天|几天|多个?工作日).{0,36}(?:仍未|未见|没有|没收到|不到账|联系不上)/.test(value)
    || /(?:等待|等了).{0,12}(?:好几|多个|超过).{0,12}(?:天|工作日).{0,24}(?:仍未|未见|没有|没收到|不到账)/.test(value)) {
    return ["退费争议", "时效争议", "退费进度"];
  }
  if (/手续费|课时费|礼品费/.test(value)) return ["退费争议", "费用核对争议", value.match(/手续费|课时费|礼品费/)?.[0]];
  if (/(?:已结营|课程已经观看|已观看).{0,20}(?:退款|退费|不予退|拒绝退)|(?:退款|退费|不予退|拒绝退).{0,20}(?:已结营|课程已经观看|已观看)/.test(value)) {
    return ["退费争议", "不符合退费标准", "已结营已观看/已结营"];
  }
  if (/(?:无社群|没有社群|未进群).{0,20}(?:超售后|售后时间|售后期|超过期限)|(?:超售后|售后时间|售后期|超过期限).{0,20}(?:无社群|没有社群|未进群)/.test(value)) {
    return ["退费争议", "不符合退费标准", "无社群已超售后时间"];
  }
  if (/态度|拉黑|踢出|移除|解散.*群/.test(value)) return ["服务争议", "售后服务问题", /态度/.test(value) ? "态度问题" : "被移除/解散社群"];
  if (/直播|回放|投屏|画面/.test(value)) return ["技术问题", "观看问题", value.match(/直播|回放|投屏|画面/)?.[0] === "回放" ? "视频回放" : value.includes("直播") ? "直播问题" : value.includes("投屏") ? "投屏异常" : "画面显示"];
  return [];
}
